// Клик по фону модалки закрывает её — но если пользователь выделяет текст
// внутри модалки мышью и курсор соскальзывает за её край, mouseup срабатывает
// уже на фоне, и раньше это тоже засчитывалось как клик "закрыть", теряя
// невведённые данные. Закрывать нужно, только если press (mousedown) САМ
// начался на фоне, а не внутри модалки — обычный клик по фону задевает и
// mousedown, и последующий click на одном и том же элементе, а выделение
// текста — нет.
//
// Не хук — плоская функция, чтобы можно было звать внутри условно
// рендерящихся блоков ({modalOpen && (...)}), которых в проекте много.
// Флаг живёт прямо на DOM-элементе (dataset), не требует useRef/useState.
export function backdropClickProps(onClose) {
  return {
    onMouseDown: (e) => {
      e.currentTarget.dataset.mousedownSelf = e.target === e.currentTarget ? "1" : "0";
    },
    onClick: (e) => {
      if (e.currentTarget.dataset.mousedownSelf === "1") onClose();
    },
  };
}
