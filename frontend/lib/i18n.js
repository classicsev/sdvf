const LanguageContext = createContext({
  locale: "ru",
  setLocale: () => {},
  t: (key) => DICT.ru[key] ?? key,
});

export function LanguageProvider({ children }) {
  const [locale, setLocaleState] = useState("ru");

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "ru" || stored === "zh") setLocaleState(stored);
  }, []);

  function setLocale(next) {
    setLocaleState(next);
    window.localStorage.setItem(STORAGE_KEY, next);
  }

  function t(key, vars) {
    const raw = DICT[locale]?.[key] ?? DICT.ru[key] ?? key;
    if (!vars) return raw;
    return Object.entries(vars).reduce((str, [k, v]) => str.replaceAll(`{${k}}`, v), raw);
  }

  return <LanguageContext.Provider value={{ locale, setLocale, t }}>{children}</LanguageContext.Provider>;
}

export function useTranslation() {
  return useContext(LanguageContext);
}
